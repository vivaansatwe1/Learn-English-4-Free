// Global Tracking States
let selectedTrack = [];
let progressIndex = 0;
let userSelectedOptionIndex = null;
let wordSpeakingPlaceholder = "";

// Launch Selected Learning Track
function startPath(ageGroupStr) {
  selectedTrack = library[ageGroupStr];
  progressIndex = 0;
  
  document.getElementById('level-badge').textContent = `AGES ${ageGroupStr}`;
  document.getElementById('age-screen').classList.add('hidden');
  document.getElementById('platform-screen').classList.remove('hidden');
  
  renderLessonCard();
}

// Generate Text View window with highlighted custom click actions
function renderLessonCard() {
  userSelectedOptionIndex = null;
  
  const currentLesson = selectedTrack[progressIndex];
  
  // Update Tracker Bar Metric View
  const progressPercent = ((progressIndex + 1) / selectedTrack.length) * 100;
  document.getElementById('progress-fill').style.width = `${progressPercent}%`;
  document.getElementById('story-tracker').textContent = `Story ${progressIndex + 1} of 10`;
  
  // Format word selectors
  document.getElementById('story-title').textContent = currentLesson.title;
  document.getElementById('story-body').innerHTML = formatPassageMarkup(currentLesson.passage);
  document.getElementById('quiz-prompt').textContent = currentLesson.question;
  
  // Clean elements
  const optionsStack = document.getElementById('quiz-options');
  optionsStack.innerHTML = '';
  document.getElementById('feedback-bar').className = 'feedback-text hidden';
  
  const checkBtn = document.getElementById('action-btn');
  checkBtn.textContent = "Check Answer";
  checkBtn.disabled = true;
  checkBtn.setAttribute("onclick", "evaluateAnswer()");

  // Build Quiz Layout List Buttons
  currentLesson.options.forEach((choiceText, index) => {
    const node = document.createElement('button');
    node.className = 'option-node';
    node.textContent = choiceText;
    node.onclick = () => selectOptionNode(index, node);
    optionsStack.appendChild(node);
  });
}

// Scan database string text looking for target words enclosed inside *asterisks*
function formatPassageMarkup(rawText) {
  return rawText.replace(/\*([^*]+)\*/g, (match, word) => {
    const cleanWord = word.replace(/[.,\/#!$%\^&\*;:{}=\-_`~()]/g, "").toLowerCase().trim();
    return `<span class="hard-word" onclick="triggerDictionaryModal('${cleanWord}')">${word}</span>`;
  });
}

// Manage multiple choice visual nodes selection
function selectOptionNode(targetIndex, elementRef) {
  const siblings = document.querySelectorAll('.option-node');
  siblings.forEach(node => node.classList.remove('selected'));
  
  elementRef.classList.add('selected');
  userSelectedOptionIndex = targetIndex;
  
  document.getElementById('action-btn').disabled = false;
}

// Evaluate targeted user multiple choice data array answers
function evaluateAnswer() {
  const currentLesson = selectedTrack[progressIndex];
  const feedbackBar = document.getElementById('feedback-bar');
  feedbackBar.classList.remove('hidden');
  
  const optionNodes = document.querySelectorAll('.option-node');
  optionNodes.forEach(node => node.removeAttribute('onclick')); // disable options after checking

  if (userSelectedOptionIndex === currentLesson.answer) {
    feedbackBar.textContent = "🎉 Excellent Work! You understood the story perfectly.";
    feedbackBar.className = "feedback-text correct";
  } else {
    feedbackBar.textContent = `❌ Incorrect. The correct answer was: "${currentLesson.options[currentLesson.answer]}"`;
    feedbackBar.className = "feedback-text wrong";
  }
  
  // Update Action footer Button state controls to move forward
  const actionBtn = document.getElementById('action-btn');
  actionBtn.textContent = "Continue";
  actionBtn.setAttribute("onclick", "advanceNextLesson()");
}

// Progress engine increment controls
function advanceNextLesson() {
  if (progressIndex + 1 < selectedTrack.length) {
    progressIndex++;
    renderLessonCard();
  } else {
    // End of 10-story course module reached!
    document.getElementById('story-body').innerHTML = "<h3>🏆 Course Complete!</h3><p>Fantastic job! You completed all 10 stories for this age group and learned advanced vocabulary words perfectly.</p>";
    document.getElementById('quiz-options').innerHTML = '';
    document.getElementById('quiz-prompt').textContent = "You've earned 100 XP!";
    document.getElementById('feedback-bar').classList.add('hidden');
    
    const actionBtn = document.getElementById('action-btn');
    actionBtn.textContent = "Return to Dashboard";
    actionBtn.setAttribute("onclick", "exitPlatform()");
  }
}

// Trigger Custom Lookup Information panel overlay
function triggerDictionaryModal(targetKeyword) {
  const infoPacket = dictionary[targetKeyword];
  if (!infoPacket) return;
  
  wordSpeakingPlaceholder = targetKeyword;
  document.getElementById('modal-word').textContent = targetKeyword.charAt(0).toUpperCase() + targetKeyword.slice(1);
  document.getElementById('modal-def').textContent = infoPacket.def;
  document.getElementById('modal-origin').textContent = infoPacket.origin;
  
  document.getElementById('dict-modal').classList.remove('hidden');
  
  // Instantly speak the text out loud using synthesized voices natively
  speakCurrentWord();
}

// Text-To-Speech Engine API activation script
function speakCurrentWord() {
  if ('speechSynthesis' in window) {
    window.speechSynthesis.cancel(); // Stop any current speech
    const voiceLine = new SpeechSynthesisUtterance(wordSpeakingPlaceholder);
    voiceLine.lang = 'en-US';
    voiceLine.rate = 0.85; // slightly slower rate for easy listening comprehension
    window.speechSynthesis.speak(voiceLine);
  } else {
    alert("Audio playback features are not fully supported natively on this version browser framework.");
  }
}

function closeModal() {
  document.getElementById('dict-modal').classList.add('hidden');
}

function exitPlatform() {
  document.getElementById('platform-screen').classList.add('hidden');
  document.getElementById('age-screen').classList.remove('hidden');
}
